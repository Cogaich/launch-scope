// Launch Scope's model: one sealed snapshot in, one ranked board out.
//
// The board ranks every pre-token protocol the snapshot can rank: the 40-protocol watchlist is the
// floor, never the ceiling, and the early radar adds every other rankable pre-token protocol below
// it, by implied value. A protocol is pre-token when DefiLlama's record carries no token for it
// (no market cap, no CoinGecko id, no symbol); the board says "records no token", never "has no
// token", because the record is not proof. Protocols whose token already trades are kept apart in
// the Live view, shown with their market caps, never mixed into the ranking.
//
// Implied value comes only from the snapshot's own figures, through one function, scopeValue:
//
//   growth     = clamp(change_7d, -50, +150) per cent (null counts as 0)
//   growthMult = 1 + growth / 100
//   maturity   = 0.75 + min(age_days, 1095) / 1095 x 0.45   (age unknown: 365 days)
//   implied    = max(1, round(tvl_usd x 0.20 x growthMult x maturity))
//
// TVL sets the scale, a strong week moves a protocol up or down by up to its own growth, and a
// protocol that has run longer with no token yet counts for more: the longer the wait, the closer
// the launch. No protocol name is ever special-cased: scopeValue scores every row the same way.

/** The snapshot's protocol entry: exactly the ten fields the sealed input carries. */
export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

/** The whole snapshot document. */
export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

/** The model's constants, as the dashboard states them. */
export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.2,
  growth_weight: 1.0,
  growth_floor: -50,
  growth_cap: 150,
  maturity_floor: 0.75,
  maturity_range: 0.45,
  maturity_days: 1095,
  unknown_age_days: 365,
};

